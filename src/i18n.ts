export const TRANSLATIONS: Record<AppLanguage, Record<TranslationKey, string>> = {
  en: EN_STRINGS,
  it: IT_STRINGS,
};

export function normalizeLanguage(raw?: string | null): AppLanguage {
  const norm = (raw ?? "").trim().toLowerCase();
  if (norm === "it" || norm.startsWith("it-") || norm.startsWith("it_")) {
    return "it";
  }
  return "en";
}

export function t(
  lang: string | null | undefined,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const resolvedLang = normalizeLanguage(lang);
  const template = TRANSLATIONS[resolvedLang][key] ?? EN_STRINGS[key] ?? String(key);
  if (!vars) {
    return template;
  }
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, varName: string) => {
    return Object.prototype.hasOwnProperty.call(vars, varName)
      ? String(vars[varName])
      : match;
  });
}
